import {
	afterAll,
	beforeAll,
	beforeEach,
	describe,
	expect,
	test,
} from 'bun:test';

import { defineRelations } from 'drizzle-orm';
import { drizzle } from 'drizzle-orm/node-postgres';
import { integer, pgTable, primaryKey, text } from 'drizzle-orm/pg-core';
import { Client } from 'pg';

import { better } from '../../src';

const parents = pgTable(
	'better_drizzle_reload_parents',
	{
		tenantKey: text('tenant_key')
			.notNull()
			.$defaultFn(() => 'generated-tenant'),
		recordKey: integer('record_key').generatedByDefaultAsIdentity(),
		label: text().notNull(),
	},
	(table) => [primaryKey({ columns: [table.tenantKey, table.recordKey] })],
);
const children = pgTable('better_drizzle_reload_children', {
	id: integer().primaryKey(),
	tenantKey: text('tenant_key').notNull(),
	parentKey: integer('parent_key').notNull(),
	label: text().notNull(),
});
const relations = defineRelations({ parents, children }, (r) => ({
	parents: {
		children: r.many.children({
			from: [r.parents.tenantKey, r.parents.recordKey],
			to: [r.children.tenantKey, r.children.parentKey],
		}),
	},
}));
const DATABASE_URL = process.env.DATABASE_URL;

describe.skipIf(!DATABASE_URL)('createMany batch reload (PostgreSQL)', () => {
	let pg: Client;
	const queries: string[] = [];
	const createClient = () =>
		better(
			drizzle({
				client: pg,
				relations,
				logger: { logQuery: (query) => queries.push(query) },
			}),
		);
	let db: ReturnType<typeof createClient>;

	beforeAll(async () => {
		pg = new Client({ connectionString: DATABASE_URL });
		await pg.connect();
		await pg.query(`
			drop table if exists better_drizzle_reload_children, better_drizzle_reload_parents;
			create table better_drizzle_reload_parents (
				tenant_key text not null,
				record_key integer generated by default as identity,
				label text not null,
				primary key (tenant_key, record_key)
			);
			create table better_drizzle_reload_children (
				id integer primary key,
				tenant_key text not null,
				parent_key integer not null,
				label text not null
			);
		`);
		db = createClient();
	});

	beforeEach(async () => {
		await pg.query(
			'truncate better_drizzle_reload_parents, better_drizzle_reload_children restart identity',
		);
		await pg.query(`
			insert into better_drizzle_reload_children values
				(1, 'generated-tenant', 1, 'first child'),
				(2, 'generated-tenant', 3, 'third child'),
				(3, 'another-tenant', 1, 'unrelated child');
		`);
		queries.length = 0;
	});

	afterAll(async () => {
		await pg.query(
			'drop table if exists better_drizzle_reload_children, better_drizzle_reload_parents',
		);
		await pg.end();
	});

	test('select reloads generated composite keys and batches related rows without exposing keys', async () => {
		const labels = ['third', 'first', 'second', 'sixth', 'fourth', 'fifth'];
		const result = await db.parents.createMany({
			data: labels.map((label) => ({ label })),
			select: { label: true, children: { select: { label: true } } },
		});
		expect(result).toEqual({
			count: labels.length,
			data: labels.map((label, index) => ({
				label,
				children:
					index === 0
						? [{ label: 'first child' }]
						: index === 2
							? [{ label: 'third child' }]
							: [],
			})),
		});
		expect(queries).toHaveLength(3);
		expect(queries[1]).toContain(' or ');
	});

	test('include preserves explicit composite-key insertion order and complete rows', async () => {
		const data = [3, 1, 6, 2, 5, 4].map((recordKey) => ({
			recordKey,
			label: `row ${recordKey}`,
		}));
		const result = await db.parents.createMany({
			data,
			include: { children: { select: { label: true } } },
		});
		expect(result).toEqual({
			count: data.length,
			data: data.map((row) => ({
				...row,
				tenantKey: 'generated-tenant',
				children:
					row.recordKey === 1
						? [{ label: 'first child' }]
						: row.recordKey === 3
							? [{ label: 'third child' }]
							: [],
			})),
		});
		expect(queries).toHaveLength(3);
	});
});
